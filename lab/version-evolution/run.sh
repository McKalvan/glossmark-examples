  Tariff:             { kind: constraint, doc: "The price schedule a customer is billed under." }
  Billing:            { kind: process, doc: "Turning a period of readings into an invoice under a tariff." }
  PeakDemand:         { kind: measure, doc: "The highest half-hourly demand a connection point drew in a billing period." }
  SupplyInterruption: { kind: event, doc: "Loss of supply at one or more connection points, planned or unplanned, with start and restoration times." }
EOF

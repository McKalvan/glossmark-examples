say "### Step 2a (classification): only a deprecation, Meter deprecated with replaced-by SmartMeter, version 1.1.1"
say ""
sed -i 's/^  Meter:             { kind: entity,/  Meter:             { kind: entity, deprecated: true, replaced-by: SmartMeter,/; s/^version: 1.1.0/version: 1.1.1/' meter-core/ontology/grid.gloss.yaml
(cd meter-core && "$GLOSS" build -q >/dev/null 2>&1)
run meter-core diff --base HEAD
side_end

# ---------------------------------------------------------------------------------------------------
say "## Step 3: MINOR, grid 1.2.0 (adds SupplyInterruption, deprecates Outage with replaced-by)"
say ""
write_grid 1.2.0 <<'EOF'
  Customer:           { kind: entity, doc: "A person or business that takes supply at one or more connection points." }
  Meter:              { kind: entity, doc: "A device that measures energy delivered to a connection point." }
  SmartMeter:         { kind: entity, is-a: Meter, doc: "A meter that reports its readings remotely." }

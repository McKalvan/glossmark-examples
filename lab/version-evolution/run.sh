# ---------------------------------------------------------------------------------------------------
cat "$OUT"
if [ "${UPDATE:-}" = 1 ]; then
  cp "$OUT" "$HERE/TRANSCRIPT.md" && echo "run.sh: wrote TRANSCRIPT.md" >&2
elif diff -u "$HERE/TRANSCRIPT.md" "$OUT" >"$WORK/transcript.diff"; then
  echo "run.sh: ok (transcript matches TRANSCRIPT.md)" >&2
else
  echo "run.sh: transcript differs from TRANSCRIPT.md:" >&2; cat "$WORK/transcript.diff" >&2; exit 1
fi

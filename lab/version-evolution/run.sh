(cd meter-core && "$GLOSS" build -q >/dev/null 2>&1)
run meter-core diff --base HEAD
for imp in $IMPORTERS; do run "$imp" check; done
side_end

say "### Step 1b (failure): the bump is written in glossmark.yaml, not in the ontology file"
say ""
say "Same doc change. The maintainer bumps \`owns.grid.version\` to 1.0.2 in \`glossmark.yaml\` and leaves the ontology file at 1.0.1."
say ""
sed -i 's/one or more connection points./one or more connection points under a single contract./' meter-core/ontology/grid.gloss.yaml
sed -i 's/tier: core,           version: 1.0.0/tier: core,           version: 1.0.2/' meter-core/glossmark.yaml
(cd meter-core && "$GLOSS" build -q >/dev/null 2>&1)
run meter-core check
run meter-core diff --base HEAD
run outage-map check
side_end

say "### Step 1c (failure): the version is only in glossmark.yaml"
say ""
say "Same doc change. \`version:\` is deleted from the ontology file; \`owns.grid.version\` in \`glossmark.yaml\` says 1.0.2."
say ""
sed -i 's/one or more connection points./one or more connection points under a single contract./; /^version: /d' meter-core/ontology/grid.gloss.yaml
sed -i 's/tier: core,           version: 1.0.0/tier: core,           version: 1.0.2/' meter-core/glossmark.yaml
(cd meter-core && "$GLOSS" build -q >/dev/null 2>&1)
run meter-core check
run meter-core diff --base HEAD
run outage-map check
side_end

# ---------------------------------------------------------------------------------------------------
say "## Step 2: MINOR, grid 1.1.0 (adds PeakDemand)"
say ""
write_grid 1.1.0 <<'EOF'
  Customer:          { kind: entity, doc: "A person or business that takes supply at one or more connection points." }
  Meter:             { kind: entity, doc: "A device that measures energy delivered to a connection point." }
  SmartMeter:        { kind: entity, is-a: Meter, doc: "A meter that reports its readings remotely." }
  MeterReading:      { kind: event, doc: "A cumulative register value taken from a meter at a point in time, in kWh." }
  ReadingCollection: { kind: process, doc: "Collecting readings from meters and making them available downstream." }
  Tariff:            { kind: entity, doc: "The price schedule a customer is billed under." }
  Billing:           { kind: process, doc: "Turning a period of readings into an invoice under a tariff." }
  Outage:            { kind: event, doc: "Loss of supply." }
  PeakDemand:        { kind: measure, doc: "The highest half-hourly demand a connection point drew in a billing period." }
EOF
release

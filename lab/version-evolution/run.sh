#!/usr/bin/env bash
# run.sh: walk meter-core's grid: namespace through PATCH, MINOR and MAJOR releases while three
# importers stay pinned at different ranges, and record what diff, check, lock, drift and landscape say.
#
#   ./run.sh            regenerate the transcript in a temp dir, print it, compare with TRANSCRIPT.md
#   UPDATE=1 ./run.sh   also overwrite TRANSCRIPT.md
#
# Nothing under this directory is modified (except TRANSCRIPT.md with UPDATE=1): every step runs on a copy
# in a fresh git repository, so `gloss diff --base HEAD` compares each release with the previous one.
set -uo pipefail
GLOSS="${GLOSS:-$(cd "$(dirname "$0")/../.." && pwd)/.tools/bin/gloss}"
HERE="$(cd "$(dirname "$0")" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
export GLOSS_ACTOR=agent:claude-code
export GIT_AUTHOR_NAME=lab GIT_AUTHOR_EMAIL=lab@example.invalid GIT_COMMITTER_NAME=lab GIT_COMMITTER_EMAIL=lab@example.invalid
IMPORTERS="billing outage-map analytics"
REPO="$WORK/repo"
OUT="$WORK/TRANSCRIPT.md"

mkdir -p "$REPO"
cp -r "$HERE/meter-core" "$HERE/billing" "$HERE/outage-map" "$HERE/analytics" "$REPO/"
cd "$REPO" || exit 2
git init -q -b main . && git add -A && git commit -qm "grid 1.0.0"

norm() { sed -E -e "s#$WORK#\$WORK#g" -e 's/ in [0-9.]+(µs|ms|s) / in Nms /'; }
say() { printf '%s\n' "$*" >>"$OUT"; }

# run <dir> <gloss args...>: one fenced block with the command, its merged output and its exit code.
# gloss lock prints its per-namespace lines in map order, which varies between runs (the file itself is stable),
# so those lines are sorted.
run() {
  local dir=$1; shift
  local out rc
  out=$(cd "$REPO/$dir" && "$GLOSS" "$@" 2>&1); rc=$?
  if [ "$1" = lock ]; then
    out=$(grep -E '^gloss lock: [a-z]+:' <<<"$out" | sort; grep -vE '^gloss lock: [a-z]+:' <<<"$out")
  fi
  printf '```text\n$ (cd %s && gloss %s)\n%s\n[exit %d]\n```\n\n' "$dir" "$*" "$out" "$rc" | norm >>"$OUT"
}

# lock_importer <dir>: run gloss lock, show what changed in glossmark.lock, and keep the new lock only
# if the resolved versions are inside the declared ranges. An importer pinned to ~1.0.0 does not adopt 1.1.0.
lock_importer() {
  local dir=$1
  run "$dir" lock
  { printf '```diff\n'; (cd "$REPO/$dir" && git diff -U0 -- glossmark.lock | grep -E '^[-+] ' || echo "(glossmark.lock unchanged)"); printf '```\n\n'; } >>"$OUT"
  local after; after=$(cd "$REPO/$dir" && "$GLOSS" check 2>&1)
  if grep -q GM106 <<<"$after"; then
    (cd "$REPO/$dir" && git checkout -q -- glossmark.lock)
    say "The new lock pins a version outside \`$dir\`'s range, so the importer keeps its old lock (\`git checkout glossmark.lock\`)."
    say ""
  fi
}

# write_grid <version>: the grid: ontology header plus the concepts on stdin.
write_grid() {
  { printf '# grid: the metering vocabulary every Gridco service shares. Importers pin it by range.\nnamespace: grid\niri: https://onto.gridco.example/grid/\nversion: %s\nconcepts:\n' "$1"; cat; } \
    >"$REPO/meter-core/ontology/grid.gloss.yaml"
}

# release <title>: build upstream, diff against the previous release, then walk every importer and the landscape.
release() {
  (cd "$REPO/meter-core" && "$GLOSS" build -q >/dev/null 2>&1)
  say "**Upstream** \`gloss diff --base HEAD\` (gate and bump classification):"; say ""
  run meter-core diff --base HEAD
  for imp in $IMPORTERS; do
    say "**$imp** ($(sed -nE 's/^ +grid: .*version: "([^"]+)".*/grid \1/p' "$REPO/$imp/glossmark.yaml")): check before re-locking, \`gloss lock\`, check after, then build and drift."; say ""
    run "$imp" check
    lock_importer "$imp"
    run "$imp" check
    (cd "$REPO/$imp" && "$GLOSS" build -q >/dev/null 2>&1)
    run "$imp" drift --fail-on dangling,violation,gap
  done
  say "**Landscape** across all four repositories:"; say ""
  run . landscape meter-core billing outage-map analytics
}

# side <title>: a failure case branched off the current release; reverted afterwards.
side_end() { git checkout -q -- . && git clean -qfd; }
commit() { git add -A && git commit -qm "$1"; }

say "# Version evolution transcript"
say ""
say "Generated by \`run.sh\` with \`$("$GLOSS" version | head -1)\`. Do not edit by hand; run \`UPDATE=1 ./run.sh\`."
say "Temporary paths are shown as \`\$WORK\` and build timings as \`Nms\`."
say ""
say "Importer policy at every step: each importer runs \`gloss check\`, then \`gloss lock\` (as GM107 tells it to), then \`gloss check\` again."
say "When the new lock would pin a version outside the importer's range, the old lock is restored: that importer stays where it was."
say ""

# ---------------------------------------------------------------------------------------------------
say "## Step 0: baseline, grid 1.0.0"
say ""
say "The committed state of the four workspaces. Every lock is current."
say ""
for imp in $IMPORTERS; do run "$imp" check; done
run . landscape meter-core billing outage-map analytics

# ---------------------------------------------------------------------------------------------------
say "## Step 1: PATCH, grid 1.0.1 (doc change on MeterReading)"

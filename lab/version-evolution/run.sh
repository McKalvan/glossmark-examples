say "### Step 4a: lockfile diagnostics GM108, GM109 and GM105 on the 2.0.0 state"
say ""
say "billing's lock deleted (GM108), then replaced by one with \`format: 99\` (GM109); then \`version:\` removed from \`mc.gloss.yaml\`, which outage-map imports at \`1.x\` (GM105)."
say ""
rm billing/glossmark.lock
run billing check
